package tema03_operadores;

public class Operaciones {
    public static void main(String[] args) {

        int numero1 = 20;
        int numero2 = 6;

        System.out.println(numero1 + numero2);
        System.out.println(numero1 - numero2);
        System.out.println(numero1 * numero2);
        System.out.println(numero1 / numero2);
        System.out.println(numero1 % numero2);

    }
}
