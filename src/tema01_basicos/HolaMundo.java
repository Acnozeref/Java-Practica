// package: indica a qué tema (carpeta) pertenece esta clase.
package tema01_basicos;

// class: contiene el código del programa.
// El nombre de la clase debe ser igual al nombre del archivo (HolaMundo.java).
public class HolaMundo {

    // main: es el punto de entrada. Java empieza a ejecutar desde aquí.
    public static void main(String[] args) {

        // System.out.println muestra un texto en la consola y salta de línea.
        // Las instrucciones se ejecutan en orden, de arriba hacia abajo,
        // y cada una termina con ;
        System.out.println("Hola, mundo");
        System.out.println("Hola, soy Kevin");
        System.out.println("Estoy aprendiendo Java");
        System.out.println("Mi objetivo es ser Backend Developer");
    }
}
